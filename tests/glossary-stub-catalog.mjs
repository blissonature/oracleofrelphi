// Run: node tests/glossary-stub-catalog.mjs
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=path=>readFileSync(resolve(root,path),'utf8');
const context=vm.createContext({URLSearchParams});
vm.runInContext(read('glossary-stub-catalog.js'),context,{filename:'glossary-stub-catalog.js'});
const m=context.RelphiGlossaryStubCatalog;
assert.ok(m,'catalog must be browser and Node test accessible');
assert.equal(m.placements.length,21);
assert.equal(m.aspects.length,11);
assert.equal(m.signs.length,12);
assert.equal(m.houses.length,12);
assert.equal(m.count(),100590336);
const ids=new Set(m.placements.map(x=>x.id));
assert.equal(ids.size,21);
assert.ok(ids.has('anti-vertex'),'Anti-Vertex must be included');
const source=read('relphi-glyph-registry-v1.js');
for(const placement of m.placements)assert.ok(source.includes("['"+placement.id+"','"),placement.id+' not in Relphi glyph registry');
const activeAspects=read('sky-chart-aspect-multiselect-v1.js');
for(const aspect of m.aspects)assert.ok(activeAspects.includes("id:'"+aspect.id+"'"),aspect.id+' not in Sky Chart aspect selectors');
const example=m.makeStub(m.defaults);
assert.equal(example.status,'stub');
assert.equal(example.source.id,'uranus');
assert.equal(example.source.retrograde,true);
assert.equal(example.aspect.degrees,180);
assert.equal(example.target.id,'part-of-fortune');
assert.equal(example.source.sign,'gemini');
assert.equal(example.source.house,10);
assert.equal(example.target.sign,'sagittarius');
assert.equal(example.target.house,3);
assert.equal(example.geometry.exactAspectPossibleFromSignPair,true);
assert.equal(example.publication.indexable,false);
assert.equal(example.interpretation.simpleDefinition,null);
assert.equal(m.makeStub(m.defaults).id,example.id,'IDs must be stable');
assert.notEqual(m.makeStub({...m.defaults,targetHouse:'4'}).id,example.id,'Target house must change ID');
assert.notEqual(m.makeStub({...m.defaults,targetSign:'capricorn'}).id,example.id,'Target sign must change ID');
assert.equal(m.makeStub({...m.defaults,targetSign:'gemini'}).geometry.exactAspectPossibleFromSignPair,false);
assert.equal(m.makeStub({...m.defaults,source:'sun',sourceRx:false,aspect:'conjunction',target:'sun',targetSign:'gemini'}).geometry.exactAspectPossibleFromSignPair,true);
assert.throws(()=>m.makeStub({...m.defaults,source:'sun',sourceRx:true}),/does not support Rx/);
assert.throws(()=>m.makeStub({...m.defaults,source:'ceres'}),/Unknown source/);
assert.throws(()=>[...m.enumerate({limit:1001})],/limit must/);
const fixed={source:'uranus',aspect:'opposition',target:'part-of-fortune',sourceSign:'gemini',sourceHouse:'10',targetSign:'sagittarius',targetHouse:'3'};
const only=[...m.enumerate({filter:fixed,limit:50})];
assert.equal(only.length,1,'One fully specified selection makes one stub');
assert.equal(only[0].id,m.makeStub({...fixed,sourceRx:false}).id);
const small=[...m.enumerate({filter:{...fixed,targetHouse:undefined},limit:3})];
assert.equal(small.length,3,'Small bounded filtered enumeration works');
assert.equal(new Set(small.map(x=>x.id)).size,3,'Each stub has a unique ID');
assert.ok(m.query(m.defaults).includes('sourceRx=1'));
const page=read('glossary-stubs.html');
assert.match(page,/<meta name="robots" content="noindex,nofollow,noarchive">/);
assert.ok(!read('sitemap.xml').includes('glossary-stubs.html'));
assert.ok(page.includes('glossary-stub-catalog.js'));
assert.ok(page.includes('glossary-stub-explorer.js'));
assert.ok(page.includes('navloader.js'));
assert.match(read('astrology-glossary.html'),/href="glossary-stubs.html"/);
console.log('Stub catalog passed: 21 placements × 11 aspects × 21 placements × (12 signs × 12 houses)² = 100,590,336 virtual base stubs.');
