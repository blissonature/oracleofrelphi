  function importThree() {
    if (!threeImportPromise) threeImportPromise = import(THREE_URL);
    return threeImportPromise;
  }

  function intersectGreatCircles(THREE, normalA, normalB, radius) {
    const direction = new THREE.Vector3().crossVectors(normalA, normalB);
    if (direction.lengthSq() < 1e-8) return null;
    direction.normalize().multiplyScalar(radius);
    return [direction.clone(), direction.clone().multiplyScalar(-1)];
  }

  function selectPair(pair, predicate) {
    if (!pair) return [null, null];
    return predicate(pair[0]) ? [pair[0], pair[1]] : [pair[1], pair[0]];
  }

  async function initThree(root) {
    const stage = root.querySelector('#vaThreeStage');
    const status = root.querySelector('#vaThreeStatus');
    if (!stage) return;

    let THREE;
    try {
      THREE = await importThree();
    } catch (error) {
      if (status) status.textContent = 'The Three.js engine could not load. The intersection formulas below remain available.';
      return;
    }
    if (!root.isConnected || document.getElementById('vertexAnglesTool') !== root) return;

    stopThreeRuntime();

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(42, 1, 0.1, 100);
    camera.position.set(0, 0, 6.2);
    camera.lookAt(0, 0, 0);

    const renderer = new THREE.WebGLRenderer({ antialias:true, alpha:true, powerPreference:'high-performance' });
    renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
    renderer.setClearColor(0xffffff, 0);
    renderer.domElement.setAttribute('role', 'img');
    renderer.domElement.setAttribute('aria-label', 'Rotatable celestial sphere showing the ecliptic, horizon, local meridian, prime vertical, and their astrological intersections.');

    stage.innerHTML = '';
    stage.appendChild(renderer.domElement);
    const labelLayer = document.createElement('div');
    labelLayer.className = 'va-label-layer';
    labelLayer.setAttribute('aria-hidden', 'false');
    stage.appendChild(labelLayer);

    const world = new THREE.Group();
    world.rotation.set(-0.43, 0.62, 0.03);
    scene.add(world);

    const radius = 2.05;
    const layers = [];
    const pointMeshes = [];
    const labels = [];
    const disposableGeometries = [];
    const disposableMaterials = [];

    function register(object, layer, baseOpacity) {
      world.add(object);
      layers.push({ object:object, layer:layer, baseOpacity:baseOpacity });
      return object;
    }

    function material(color, opacity) {
      const value = new THREE.MeshBasicMaterial({
        color:color,
        transparent:true,
        opacity:opacity,
        depthWrite:false
      });
      disposableMaterials.push(value);
      return value;
    }

    function greatCircle(normal, color, layer) {
      const geometry = new THREE.TorusGeometry(radius, 0.018, 6, 256);
      disposableGeometries.push(geometry);
      const mesh = new THREE.Mesh(geometry, material(color, 0.96));
      mesh.quaternion.setFromUnitVectors(new THREE.Vector3(0, 0, 1), normal.clone().normalize());
      register(mesh, layer, 0.96);
      return mesh;
    }

    function point(position, color, layer, focusName, labelText, labelClass) {
      const geometry = new THREE.SphereGeometry(0.085, 18, 14);
      disposableGeometries.push(geometry);
      const mesh = new THREE.Mesh(geometry, material(color, 1));
      mesh.position.copy(position);
      mesh.userData.focus = focusName;
      mesh.userData.layer = layer;
      register(mesh, layer, 1);
      pointMeshes.push(mesh);
      addLabel(labelText, position, layer, focusName, labelClass || 'is-angle');
      return mesh;
    }

    function addLabel(text, position, layer, focusName, extraClass) {
      const element = document.createElement(focusName ? 'button' : 'span');
      if (focusName) {
        element.type = 'button';
        element.dataset.vaFocusPoint = focusName;
        element.setAttribute('aria-label', 'Focus ' + text);
        element.addEventListener('click', function () { setFocus(focusName); });
      }
      element.className = 'va-three-label' + (extraClass ? ' ' + extraClass : '');
      element.textContent = text;
      labelLayer.appendChild(element);
      labels.push({
        element:element,
        localPosition:position.clone(),
        layer:layer,
        focusName:focusName || '',
        built:true,
        allowed:true
      });
      return element;
    }

    const sphereGeometry = new THREE.SphereGeometry(radius, 28, 20);
    disposableGeometries.push(sphereGeometry);
    const sphere = new THREE.Mesh(sphereGeometry, material(COLORS.sphere, 0.075));
    sphere.material.wireframe = true;
    register(sphere, 'sphere', 0.075);

    const axisMaterial = new THREE.LineBasicMaterial({ color:0x555555, transparent:true, opacity:0.16, depthWrite:false });
    disposableMaterials.push(axisMaterial);
    const axisGeometry = new THREE.BufferGeometry().setFromPoints([
      new THREE.Vector3(-radius * 1.12, 0, 0), new THREE.Vector3(radius * 1.12, 0, 0),
      new THREE.Vector3(0, -radius * 1.12, 0), new THREE.Vector3(0, radius * 1.12, 0),
      new THREE.Vector3(0, 0, -radius * 1.12), new THREE.Vector3(0, 0, radius * 1.12)
    ]);
    disposableGeometries.push(axisGeometry);
    const axes = new THREE.LineSegments(axisGeometry, axisMaterial);
    register(axes, 'orientation', 0.16);

    const observerGeometry = new THREE.SphereGeometry(0.07, 16, 12);
    disposableGeometries.push(observerGeometry);
    const observer = new THREE.Mesh(observerGeometry, material(COLORS.observer, 1));
    register(observer, 'observer', 1);

    const horizonNormal = new THREE.Vector3(0, 1, 0);
    const meridianNormal = new THREE.Vector3(1, 0, 0);
    const primeNormal = new THREE.Vector3(0, 0, 1);
    const eclipticNormal = new THREE.Vector3(0.38, 0.88, 0.28).normalize();

    greatCircle(horizonNormal, COLORS.horizon, 'horizon');
    greatCircle(meridianNormal, COLORS.meridian, 'meridian');
    greatCircle(primeNormal, COLORS.prime, 'prime');
    greatCircle(eclipticNormal, COLORS.ecliptic, 'ecliptic');

    const horizonPair = selectPair(intersectGreatCircles(THREE, eclipticNormal, horizonNormal, radius), function (p) { return p.x > 0; });
    const meridianPair = selectPair(intersectGreatCircles(THREE, eclipticNormal, meridianNormal, radius), function (p) { return p.y > 0; });
    const vertexPair = selectPair(intersectGreatCircles(THREE, eclipticNormal, primeNormal, radius), function (p) { return p.x < 0; });

    point(horizonPair[0], COLORS.ecliptic, 'horizon-points', 'horizon', 'ASC', 'is-angle');
    point(horizonPair[1], COLORS.ecliptic, 'horizon-points', 'horizon', 'DSC', 'is-angle');
    point(meridianPair[0], COLORS.ecliptic, 'meridian-points', 'meridian', 'MC', 'is-angle');
    point(meridianPair[1], COLORS.ecliptic, 'meridian-points', 'meridian', 'IC', 'is-angle');
    point(vertexPair[0], COLORS.point, 'vertex-points', 'vertex', 'VERTEX Vx', 'is-vertex');
    point(vertexPair[1], COLORS.point, 'vertex-points', 'vertex', 'Anti-Vertex', 'is-vertex');

    addLabel('East', new THREE.Vector3(radius * 1.24, 0, 0), 'orientation', '', 'is-cardinal');
    addLabel('West', new THREE.Vector3(-radius * 1.24, 0, 0), 'orientation', '', 'is-cardinal');
    addLabel('Zenith', new THREE.Vector3(0, radius * 1.24, 0), 'orientation', '', 'is-cardinal');
    addLabel('Nadir', new THREE.Vector3(0, -radius * 1.24, 0), 'orientation', '', 'is-cardinal');
    addLabel('North', new THREE.Vector3(0, 0, radius * 1.24), 'orientation', '', 'is-cardinal');
    addLabel('South', new THREE.Vector3(0, 0, -radius * 1.24), 'orientation', '', 'is-cardinal');
    addLabel('Birthplace', new THREE.Vector3(0, 0.16, 0), 'observer', '', 'is-observer');

    const raycaster = new THREE.Raycaster();
    const pointer = new THREE.Vector2();
    const activePointers = new Map();
    let previousPinchDistance = 0;
    let pointerStart = null;
    let animationFrame = 0;
    let stopped = false;

    function resize() {
      const width = Math.max(1, stage.clientWidth);
      const height = Math.max(1, stage.clientHeight);
      renderer.setSize(width, height, false);
      camera.aspect = width / height;
      camera.updateProjectionMatrix();
    }

    const resizeObserver = new ResizeObserver(resize);
    resizeObserver.observe(stage);
    resize();

    function clampCamera() {
      camera.position.z = Math.max(4.1, Math.min(9.2, camera.position.z));
    }

    function pointerDistance() {
      const values = Array.from(activePointers.values());
      if (values.length < 2) return 0;
      const dx = values[0].x - values[1].x;
      const dy = values[0].y - values[1].y;
      return Math.hypot(dx, dy);
    }

    function onPointerDown(event) {
      renderer.domElement.setPointerCapture(event.pointerId);
      activePointers.set(event.pointerId, { x:event.clientX, y:event.clientY, previousX:event.clientX, previousY:event.clientY });
      if (activePointers.size === 1) pointerStart = { x:event.clientX, y:event.clientY };
      if (activePointers.size === 2) previousPinchDistance = pointerDistance();
      renderer.domElement.classList.add('is-dragging');
    }

    function onPointerMove(event) {
      const state = activePointers.get(event.pointerId);
      if (!state) return;
      state.previousX = state.x;
      state.previousY = state.y;
      state.x = event.clientX;
      state.y = event.clientY;

      if (activePointers.size === 1) {
        const dx = state.x - state.previousX;
        const dy = state.y - state.previousY;
        world.rotation.y += dx * 0.007;
        world.rotation.x += dy * 0.007;
        world.rotation.x = Math.max(-Math.PI * 0.95, Math.min(Math.PI * 0.95, world.rotation.x));
      } else if (activePointers.size >= 2) {
        const distance = pointerDistance();
        if (previousPinchDistance > 0 && distance > 0) {
          camera.position.z *= previousPinchDistance / distance;
          clampCamera();
        }
        previousPinchDistance = distance;
      }
    }

    function tryRaycast(event) {
      if (!pointerStart) return;
      const moved = Math.hypot(event.clientX - pointerStart.x, event.clientY - pointerStart.y);
      if (moved > 7) return;
      const rect = renderer.domElement.getBoundingClientRect();
      pointer.x = ((event.clientX - rect.left) / rect.width) * 2 - 1;
      pointer.y = -((event.clientY - rect.top) / rect.height) * 2 + 1;
      raycaster.setFromCamera(pointer, camera);
      const hits = raycaster.intersectObjects(pointMeshes, false);
      if (hits.length && hits[0].object.userData.focus) setFocus(hits[0].object.userData.focus);
    }

    function onPointerUp(event) {
      if (activePointers.size === 1) tryRaycast(event);
      activePointers.delete(event.pointerId);
      if (renderer.domElement.hasPointerCapture(event.pointerId)) renderer.domElement.releasePointerCapture(event.pointerId);
      if (activePointers.size < 2) previousPinchDistance = 0;
      if (!activePointers.size) {
        renderer.domElement.classList.remove('is-dragging');
        pointerStart = null;
      }
    }

    function onWheel(event) {
      event.preventDefault();
      camera.position.z += event.deltaY * 0.006;
      clampCamera();
    }

    renderer.domElement.addEventListener('pointerdown', onPointerDown);
    renderer.domElement.addEventListener('pointermove', onPointerMove);
    renderer.domElement.addEventListener('pointerup', onPointerUp);
    renderer.domElement.addEventListener('pointercancel', onPointerUp);
    renderer.domElement.addEventListener('wheel', onWheel, { passive:false });

    function projectLabels() {
      scene.updateMatrixWorld(true);
      const width = stage.clientWidth;
      const height = stage.clientHeight;
      const cameraDirection = camera.position.clone().normalize();

      labels.forEach(function (entry) {
        if (!entry.built) {
          entry.element.hidden = true;
          return;
        }
        entry.element.hidden = false;
        const worldPosition = entry.localPosition.clone().applyMatrix4(world.matrixWorld);
        const projected = worldPosition.clone().project(camera);
        const x = (projected.x * 0.5 + 0.5) * width;
        const y = (-projected.y * 0.5 + 0.5) * height;
        entry.element.style.left = x.toFixed(1) + 'px';
        entry.element.style.top = y.toFixed(1) + 'px';

        let facing = 1;
        if (entry.localPosition.lengthSq() > 0.05) {
          const outward = worldPosition.clone().normalize();
          facing = Math.max(0.28, Math.min(1, (outward.dot(cameraDirection) + 1.1) / 1.7));
        }
        entry.element.style.opacity = String((entry.allowed ? 1 : 0.15) * facing);
      });
    }

    function applyVisibility() {
      layers.forEach(function (entry) {
        const built = layerRequirement(entry.layer) <= buildStep;
        const allowed = focusAllows(entry.layer);
        entry.object.visible = built;
        const materials = Array.isArray(entry.object.material) ? entry.object.material : [entry.object.material];
        materials.filter(Boolean).forEach(function (mat) {
          mat.opacity = allowed ? entry.baseOpacity : Math.min(0.09, entry.baseOpacity * 0.16);
        });
      });
      labels.forEach(function (entry) {
        entry.built = layerRequirement(entry.layer) <= buildStep;
        entry.allowed = focusAllows(entry.layer);
      });
    }

    function rotate(direction) {
      const step = Math.PI / 12;
      if (direction === 'left') world.rotation.y -= step;
      if (direction === 'right') world.rotation.y += step;
      if (direction === 'up') world.rotation.x -= step;
      if (direction === 'down') world.rotation.x += step;
      if (direction === 'reset') {
        world.rotation.set(-0.43, 0.62, 0.03);
        camera.position.z = 6.2;
      }
    }

    function animate() {
      if (stopped || !root.isConnected || document.getElementById('vertexAnglesTool') !== root) {
        stop();
        return;
      }
      renderer.render(scene, camera);
      projectLabels();
      animationFrame = requestAnimationFrame(animate);
    }

    function stop() {
      if (stopped) return;
      stopped = true;
      cancelAnimationFrame(animationFrame);
      resizeObserver.disconnect();
      renderer.domElement.removeEventListener('pointerdown', onPointerDown);
      renderer.domElement.removeEventListener('pointermove', onPointerMove);
      renderer.domElement.removeEventListener('pointerup', onPointerUp);
      renderer.domElement.removeEventListener('pointercancel', onPointerUp);
      renderer.domElement.removeEventListener('wheel', onWheel);
      disposableGeometries.forEach(function (geometry) { geometry.dispose(); });
      disposableMaterials.forEach(function (mat) { mat.dispose(); });
      renderer.dispose();
    }

    threeRuntime = {
      root:root,
      applyVisibility:applyVisibility,
      rotate:rotate,
      stop:stop
    };

    root.querySelectorAll('[data-va-rotate]').forEach(function (button) {
      button.addEventListener('click', function () {
        if (threeRuntime && threeRuntime.root === root) threeRuntime.rotate(button.dataset.vaRotate);
      });
    });

    applyVisibility();
    animate();
  }

  function bindTool() {
    const root = document.getElementById('vertexAnglesTool');
    if (!root) return;
    root.querySelectorAll('[data-va-focus]').forEach(function (button) {
      button.addEventListener('click', function () { setFocus(button.dataset.vaFocus); });
    });
    root.querySelectorAll('[data-va-step]').forEach(function (button) {
      button.addEventListener('click', function () {
        buildStep = Math.max(0, Math.min(5, Number(button.dataset.vaStep) || 0));
        focus = buildStep === 2 ? 'horizon' : buildStep === 3 ? 'meridian' : buildStep === 4 ? 'vertex' : 'all';
        sync();
      });
    });
    root.querySelector('#vaOpenCampanus')?.addEventListener('click', function () {
      stopThreeRuntime();
      const systems = tabs.querySelector('[data-kind="systems"]');
      systems?.click();
      requestAnimationFrame(function () {
        const campanus = grid.querySelector('[data-system="Campanus"]');
        campanus?.click();
        campanus?.scrollIntoView({
          behavior:matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth',
          block:'center'
        });
      });
    });
    sync();
    initThree(root);
  }

  function renderTool() {
    stopThreeRuntime();
    document.querySelectorAll('.foundation-tabs [data-kind]').forEach(function (button) {
      button.setAttribute('aria-pressed', 'false');
    });
    const tab = tabs.querySelector('[data-kind="angles"]');
    tab?.setAttribute('aria-pressed', 'true');
    title.textContent = 'Vertex & Local Angles';
    if (note) {
      note.hidden = false;
      note.textContent = 'Rotate a three-dimensional celestial sphere and trace how the ecliptic produces ASC/DSC, MC/IC, and Vertex/Anti-Vertex by intersecting three different local great circles.';
    }
    focus = 'all';
    buildStep = 5;
    grid.innerHTML = toolMarkup();
    bindTool();
  }

  installStyles();
  const tab = addTab();
  tab.addEventListener('click', renderTool);
